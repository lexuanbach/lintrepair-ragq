"""Assemble every headline number in the paper into a single canonical file,
results/paper_numbers.json, by reading the authoritative per-experiment result
files. No recomputation and no API calls: this is the paper<->artifact contract.

Run:  python experiments/make_paper_numbers.py
"""
from __future__ import annotations
import json, os

HERE = os.path.dirname(os.path.abspath(__file__)); R = os.path.join(HERE, "results")
def load(name): return json.load(open(os.path.join(R, name)))

summ   = load("summary_FROZEN.json")      # detection (frozen pilot)
cross  = load("cross_model.json")         # 18-model repair rows + pooled tests
rev    = load("revision_analyses.json")   # stratified / family / capability
inter  = load("interaction_and_losses.json")  # interaction slope + loss breakdown + detector audit
lintq  = load("lintq_comparison.json")    # LintQ head-to-head
bugs   = load("bugs4q_summary.json")      # independently-sourced real bugs
# The manuscript reports the 10-program Cirq cross-SDK probe (cirqdefects.json);
# crosssdk_cirq.json is an earlier 8-program pilot and is not the reported source.
try:    cirq = load("cirqdefects.json")
except Exception: cirq = None

det = summ["detection"]
paper = {
    "_provenance": "Generated by experiments/make_paper_numbers.py from the "
                   "per-experiment result files; every value is read, not recomputed.",
    "benchmark": {
        "programs": summ["n_instances"], "defective": summ["n_buggy"],
        "clean": summ["n_clean"], "families": summ["n_categories"],
    },
    "models": {"total": len(cross["rows"]),
               "names": [r["model"] for r in cross["rows"]]},

    # RQ1 -- detection (Table 1)
    "rq1_detection": {
        "static": {"recall": round(det["static"]["recall"], 3), "precision": det["static"]["precision"]},
        "llm":    {"recall": round(det["llm"]["recall"], 3),    "precision": det["llm"]["precision"]},
        "union":  {"recall": round(det["union"]["recall"], 3),  "precision": det["union"]["precision"]},
        # Sourced from the expanded 40-negative run, not the 8-negative pilot in
        # summary.json. Both are zero, but only one has the right denominator.
        "false_positives_on_40_negatives": (
            rev.get("expanded_negatives", {}).get("union_false_positives", det["union"]["fp"])
        ),
        "lintq_default_highprec_recall": lintq["lintq_default_highprec"].get("recall", 0.0),
        "lintq_all_checkers": lintq["lintq_all_checkers"],
    },

    # RQ2 -- repair crossover (Table 2, Fig 4)
    "rq2_repair": {
        "pooled_B2_vs_B0": cross["pooled"]["B2_vs_B0"],
        "stratified_by_kind": rev["stratified_by_kind"],
        "capability_correlation": rev["capability_corr"],
        "interaction_regression": inter["interaction"],
        "wins_by_kind": inter["wins_by_kind"],
        "losses_by_kind": inter["losses_by_kind"],
        "losses_by_kind_capability": inter["losses_by_kind_capability"],
        "family_level_pooled": rev["family_level_pooled"],
        "crossover_table": [
            {"model": r["model"], "rho": r.get("rho_hat"),
             "B0": r["B0"]["p"], "B2": r["B2"]["p"],
             "B3": r["B3"]["p"], "B4": r["B4"]["p"]}
            for r in cross["rows"]
        ],
    },

    # RQ3 -- debiasing is itself capability-governed
    "rq3_debiasing": {
        "B3_vs_B2": cross["pooled"]["B3_vs_B2"],
        "B4_vs_B2": cross["pooled"]["B4_vs_B2"],
        "B3_vs_B4_leakage_gap": cross["pooled"]["B3_vs_B4"],
    },

    # Controlled dissection + detector audit
    "dissection": {
        "detector_audit": inter["detector_audit"],
        "see_also": ["anchoring_controls.json (B0filler matched controls)",
                     "passk.json (pass@5 robustness)",
                     "mutation_crossover.json (powered n=115 silent set)",
                     "retrieval_sensitivity.json (top-k budget dial)"],
    },

    # Replication on independently-sourced / cross-SDK bugs
    "replication": {
        "bugs4q": {"reproducibility": bugs["reproducibility"],
                   "pooled_B2_B0": bugs["pooled_B2_B0"],
                   "strong_silent_anchoring": bugs.get("strong_silent_anchoring")},
        "cross_sdk_cirq_negative": (cirq if cirq is not None else "cirqdefects.json"),
    },
}

out = os.path.join(R, "paper_numbers.json")
json.dump(paper, open(out, "w"), indent=2)
print(f"wrote {out}")
print(f"  models={paper['models']['total']}  "
      f"detection union recall={paper['rq1_detection']['union']['recall']}  "
      f"pooled B2-B0={paper['rq2_repair']['pooled_B2_vs_B0']['diff']} "
      f"({paper['rq2_repair']['pooled_B2_vs_B0']['wins']}/"
      f"{paper['rq2_repair']['pooled_B2_vs_B0']['losses']})")
print(f"  interaction slope={paper['rq2_repair']['interaction_regression']['slope']} "
      f"crossing rho={paper['rq2_repair']['interaction_regression']['zero_crossing_rho']}")
